#!/usr/bin/env python3
"""Writes the on-chip bench's cases (device/main/generated/cases.c): scripts/measure.py's cases, each
with the host CLI's derivative, which the S3 must reproduce byte for byte."""
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import measure  # noqa: E402

ANGLES = {"DEG": 0, "RAD": 1, "GRAD": 2}


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(path):
    rows = []
    for name, expr, var, angle, op in measure.all_cases():
        args = ["derive", expr, var, angle] if op == "derive" else ["simplify", expr, angle]
        p = subprocess.run([measure.CLI, "--arena", "65536"] + args, stdout=subprocess.PIPE, text=True)
        if p.returncode != 0:
            print(f"skipped {name}: {p.stdout.strip()}")
            continue
        want = p.stdout.rstrip("\n")
        rows.append(f"    {{{c_str(name)}, {c_str(expr)}, {ord(var) - ord('A')}, {ANGLES[angle]}, "
                    f"{int(op == 'simplify')}, {len(expr)}, {c_str(want)}}},")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write("/* generated by scripts/device_cases.py: do not edit */\n#include \"cases.h\"\n\n")
        f.write("const bench_case cases[] = {\n" + "\n".join(rows) + "\n};\n")
        f.write(f"const int case_count = {len(rows)};\n")
    print(f"{len(rows)} cases written to {path}")


if __name__ == "__main__":
    main(sys.argv[1])
