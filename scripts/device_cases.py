#!/usr/bin/env python3
"""Writes the on-chip bench's cases (device/main/generated/cases.c): scripts/measure.py's cases, each
with the host CLI's derivative, which the S3 must reproduce byte for byte. CASIM_BENCH_ARENA=N runs both sides at N
bytes of arena (at most the bench's 32,768); unset, the host answers at 65,536 and the chip runs at 32,768."""
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import measure  # noqa: E402

ANGLES = {"DEG": 0, "RAD": 1, "GRAD": 2}
STATUS = {"TOO_LONG": 3, "BAD_ARG": 4, "NO_ROOM": 5, "NOT_POLYNOMIAL": 6, "NOT_NUMERIC": 7, "NOT_INTEGRABLE": 8,
          "PARTIAL": 9, "UNDEFINED": 10, "IMPROPER": 11, "UNDECIDED": 12, "NO_CLOSED_FORM": 13, "DECIMAL_FORM": 14}


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(path):
    rows = []
    arena = os.environ.get("CASIM_BENCH_ARENA", "")
    if arena and not (arena.isdigit() and 0 < int(arena) <= 32768):
        sys.exit(f"CASIM_BENCH_ARENA={arena}: a byte count up to the bench's 32768")
    models = {"STU": 1, "33": 33, "35": 35}
    for name, expr, var, angle, op, repl, model in measure.all_cases():
        args = measure.cli_args(expr, var, angle, op, repl, model)
        p = subprocess.run([measure.CLI, "--arena", arena or "65536"] + args, stdout=subprocess.PIPE, text=True)
        first = p.stdout.strip().split("\n")[0].split(" ")[0] if p.stdout.strip() else ""
        status = 0 if p.returncode == 0 else STATUS.get(first)
        if status is None:
            print(f"skipped {name}: {p.stdout.strip()}")
            continue
        want = (p.stdout.rstrip("\n") if status == 0 else p.stdout.rstrip("\n")[8:] if status == 9   # PARTIAL: its text
                else p.stdout.rstrip("\n").split("\n", 1)[1] if status == 14 else "")                 # DECIMAL_FORM's answer
        if len(want.encode()) >= 16000:
            print(f"skipped {name}: its {len(want.encode())}-byte text exceeds the bench's buffer")
            continue
        ops = ["derive", "simplify", "expand", "collect", "subst", "solve", "integrate", "factor", "defint", "pdiv", "pgcd",
               "cancel", "partfrac", "taylor", "limit", "sum"]
        lo, hi = (repl.split("|", 1) if op in ("defint", "taylor", "limit", "sum") else (repl or "", ""))   # point, n, side
        rows.append(f"    {{{c_str(name)}, {c_str(expr)}, {ord(var) - ord('A')}, {ANGLES[angle]}, "
                    f"{ops.index(op)}, {c_str(lo)}, {models[model]}, {len(expr)}, {status}, {c_str(want)}, {c_str(hi)}}},")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write("/* generated by scripts/device_cases.py: do not edit */\n#include \"cases.h\"\n\n")
        f.write("const bench_case cases[] = {\n" + "\n".join(rows) + "\n};\n")
        f.write(f"const int case_count = {len(rows)};\n")
        f.write(f"const unsigned bench_arena = {arena or 32768};\n")
    print(f"{len(rows)} cases written to {path}, arena {arena or '65536 on the host, 32768 on the chip'}")


if __name__ == "__main__":
    main(sys.argv[1])
